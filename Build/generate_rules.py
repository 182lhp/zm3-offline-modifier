"""Deterministic rule compiler. Only Rules/definitions.json and pinned Inputs are edited."""
from pathlib import Path
import argparse,copy,hashlib,json

def encode(value):return (json.dumps(value,ensure_ascii=False,sort_keys=True,separators=(',',':'))+'\n').encode('utf-8')
def sha(value):return hashlib.sha256(value).hexdigest()
def compile_rules(source):
    definition=json.loads((source/'Rules/definitions.json').read_text(encoding='utf-8'));inputs={}
    if definition['format']!=1:raise ValueError('Unsupported rule source format')
    for name,expected in definition['inputs'].items():
        if Path(name).name!=name:raise ValueError('Invalid rule input path')
        raw=(source/'Rules/Inputs'/name).read_bytes()
        if sha(raw)!=expected:raise ValueError('Rule input changed without a reviewed source revision: '+name)
        inputs[name]=json.loads(raw.decode('utf-8-sig'))
    rules=definition['rules'];inv=rules['inventory'];pet=rules['pet'];vip=rules['vip'];garden=rules['garden']
    for thresholds in [vip['thresholds'],garden['thresholds'],garden['templeThresholds']]:
        if thresholds[0]!=0 or thresholds!=sorted(set(thresholds)):raise ValueError('Non-increasing rule thresholds')
    if inv['petsVipLevel']>=len(vip['thresholds']) or pet['potentialMax']!=100 or len(garden['thresholds'])!=9 or len(garden['templeThresholds'])!=5:raise ValueError('Incompatible serialization rules')
    refs=copy.deepcopy(inputs['ref_all.json']);editor=inputs['editor_server_zmxy3.json'];supplemented=[]
    # Same explicit constructors as the former runtime supplementation, now once at build time.
    keys=['ehp','emp','eatt','edef','emiss','ecrit','eahp','eamp','magicdef','speed','eatblood']
    from decimal import Decimal,InvalidOperation
    for row in editor['items']:
        code=row.get('fillName');args=row.get('rawArgs',[])
        if not code or code in refs['petequip'] or row.get('class')!='PetEquipObj' or row.get('type')!='zbjn' or len(args)<18:continue
        try:values=[Decimal(str(v)) for v in args[7:18]]
        except (InvalidOperation,ValueError):continue
        if values[0]<0 or any(v!=0 for v in values[1:]):continue
        refs['petequip'][code]={key:'0' for key in keys};refs['petequip'][code]['ehp']=str(args[7]);supplemented.append(code)
    payload=dict(format=1,revision=definition['revision'],gameSha256=definition['gameSha256'],sourceSha256=sha(encode(definition)),inputs=definition['inputs'],provenance=definition['provenance'],supplementedSpirits=sorted(supplemented),rules=rules,
        catalog=inputs['library_final.json'],references=refs,equipmentStrength=inputs['equip_strength.json'],petEquipmentStrength=inputs['peteq_strength.json'],official=inputs['official_zmxy3.json'],extreme=editor['extreme'],petSkillDescriptions=editor['petSkillDesc'],specialPets=inputs['special_pets.json']['pets'],fieldNames=inputs['editor_field_names.json']['field_cn'])
    for row in payload['catalog']['items']:
        if row.get('class')=='PetEquipObj' and row.get('fill') not in refs['petequip']:raise ValueError('Missing pet equipment reference: '+row['fill'])
    return encode(payload)

def generate(source,check=False):
    raw=compile_rules(source);digest=sha(raw)
    outputs={source/'Rules/generated.json':raw,source/'Build/runtime/rules_stamp.py':('# Generated by Build/generate_rules.py; do not edit.\nEXPECTED_SHA256='+repr(digest)+'\n').encode(),source/'GameRules.Generated.cs':('// Generated by Build/generate_rules.py; do not edit.\nnamespace GmStudio;\ninternal static partial class GameRules {internal const string ExpectedSha256="'+digest+'";}\n').encode()}
    for path,body in outputs.items():
        if check:
            if not path.exists() or path.read_bytes()!=body:raise ValueError('Stale generated rule artifact: '+str(path))
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(body)
    return dict(revision=json.loads(raw)['revision'],sha256=digest,bytes=len(raw))
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--source',type=Path,default=Path(__file__).resolve().parent.parent);p.add_argument('--check',action='store_true');a=p.parse_args();print(json.dumps(generate(a.source,a.check)))
